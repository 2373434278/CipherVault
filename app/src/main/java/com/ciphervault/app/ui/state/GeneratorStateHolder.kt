package com.ciphervault.app.ui.state

import androidx.compose.runtime.Stable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableIntStateOf
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.ciphervault.app.domain.PasswordGenerator
import com.ciphervault.app.domain.PasswordOptions

/**
 * 密码生成器状态持有者。
 *
 * 页面只负责渲染与转发意图；选项变化后立即重新生成，逻辑可脱离 Compose 单测。
 */
@Stable
class GeneratorStateHolder {
    var passphraseMode by mutableStateOf(false)
        private set
    var options by mutableStateOf(PasswordOptions())
        private set
    var wordCount by mutableIntStateOf(5)
        private set
    var generated by mutableStateOf("")
        private set

    init {
        regenerate()
    }

    val strength: Int get() = PasswordGenerator.strength(generated)

    fun setMode(passphrase: Boolean) {
        passphraseMode = passphrase
        regenerate()
    }

    fun changeWordCount(count: Int) {
        wordCount = count.coerceIn(3, 8)
        regenerate()
    }

    fun setLength(length: Int) = updateOptions { it.copy(length = length) }

    fun setUppercase(enabled: Boolean) = updateOptions { it.copy(uppercase = enabled) }

    fun setLowercase(enabled: Boolean) = updateOptions { it.copy(lowercase = enabled) }

    fun setDigits(enabled: Boolean) = updateOptions { it.copy(digits = enabled) }

    fun setSymbols(enabled: Boolean) = updateOptions { it.copy(symbols = enabled) }

    fun regenerate() {
        generated = if (passphraseMode) {
            PasswordGenerator.generatePassphrase(wordCount)
        } else {
            PasswordGenerator.generate(options)
        }
    }

    private fun updateOptions(transform: (PasswordOptions) -> PasswordOptions) {
        options = transform(options)
        regenerate()
    }
}
